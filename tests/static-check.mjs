import { readFileSync, existsSync } from 'node:fs';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const app = readFileSync(path.join(root, 'src/app.js'), 'utf8');
const html = readFileSync(path.join(root, 'index.html'), 'utf8');
const css = readFileSync(path.join(root, 'src/styles.css'), 'utf8');
assert.ok(existsSync(path.join(root, 'diagnostics/camera-only.html')), 'camera-only diagnostic exists');
for (const marker of ['camera-video','ar-canvas','products','camera-toggle','retry-tracking','capture']) {
  assert.ok(html.includes('id="' + marker + '"'), 'HTML component exists: ' + marker);
}
assert.match(app, /getUserMedia/, 'camera input is requested on user action');
assert.match(app, /state\.stream\s*=\s*stream/, 'camera stream has its own lifecycle');
assert.match(app, /void loadEngine/, 'AI model loading is asynchronous and independent');
assert.match(app, /instance\.close\(\)/, 'late model is disposed after session cancellation');
assert.match(app, /state\.epoch/, 'camera session tokens protect stale requests');
assert.match(app, /requestAnimationFrame/, 'video overlay rendering uses frame loop');
assert.match(app, /pose_landmarker_lite/, 'lite pose model is configured');
assert.match(app, /hand_landmarker/, 'hand tracking is configured');
assert.match(app, /face_landmarker/, 'face tracking is configured');
assert.match(css, /\.camera-layers\.flipped/, 'video and AR overlay are mirrored consistently');
assert.ok(existsSync(path.join(root, 'diagnostics/tracking.html')), 'model diagnostic exists');
assert.ok(html.includes('id="tracking-debug"'), 'debug report is available in main app');
assert.ok(app.includes('vision_bundle.mjs'), 'use official ESM bundle');
assert.ok(app.includes('@mediapipe/tasks-vision@'), 'use versioned WASM and ESM');
assert.ok(app.includes("const MEDIAPIPE_VERSION = '0.10.21'"), 'use pinned version');
assert.ok(!app.includes('@0.10.22/+esm'), 'remove old broken version import');
assert.ok(app.includes('faceLandmarks'), 'read face result correctly');
assert.ok(app.includes('unpkg.com'), 'provide alternate CDN');
assert.ok(html.includes('ALPHA 0.4'), 'HTML and release version updated');
assert.ok(html.includes('src="./src/app.js?v=20261117-alpha040"'), 'JS has explicit cache busting version');
assert.ok(html.includes('href="./src/styles.css?v=20261117-alpha040"'), 'CSS has explicit cache busting version');
assert.ok(html.includes('id="runtime-version"'), 'build verification element exists');
assert.ok(app.includes("const BUILD_ID = '2026.11.17.040'"), 'runtime identifies compiled source');
assert.ok(app.includes('state.inferenceFrames += 1'), 'AI FPS measured independently from render frames');
assert.ok(html.includes('id="sync-canvas"'), 'frame synchronized output exists');
assert.ok(html.includes('id="mode-sync"') && html.includes('id="mode-fast"'), 'sync/fast mode selectors exist');
assert.ok(app.includes('model.detectForVideo(sampleCanvas, frameTime)'), 'synchronized inference uses captured image');
assert.ok(app.includes('ctx.drawImage(sampleCanvas,'), 'synchronized result renders that same frame');
assert.ok(app.includes('state.syncFrameReady'), 'synchronized display waits for result');
assert.ok(app.includes('LIVE_INTERVAL_MS'), 'fast tracking pace is configurable');
assert.ok(existsSync(path.join(root, 'tests/frame-sync.smoke.mjs')), 'frame sync browser mock regression exists');
console.log('RAWNAK FIT AI static smoke tests passed (not a real-camera test).');
