export function getCaptureProfile(category) {
  return PROFILES[category] || null;
}
export function captureProgress(category, numberOfPhotos) {
  const p = getCaptureProfile(category);
  if (!p) return { count: numberOfPhotos, previewMinimum: 0, verifiedMinimum: 0, verifiedTarget: 0, level: 'unknown', label: 'اختار الفئة' };
  const count = Math.max(0, Number(numberOfPhotos) || 0);
  return { count, previewMinimum: p.previewMin, verifiedMinimum: p.verifiedMin, verifiedTarget: p.verifiedTarget,
    level: count >= p.verifiedMin ? 'reviewable' : count >= p.previewMin ? 'preview' : 'incomplete',
    label: count >= p.verifiedMin ? 'مكتمل بالعدد — باقي مراجعة الجودة' : count >= p.previewMin ? 'مبدئي فقط' : 'الصور أقل من الحد المبدئي' };
}
